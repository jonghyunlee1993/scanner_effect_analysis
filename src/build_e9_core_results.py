          + ", ".join(f"{data.ENCODER_LABEL[e]} {retrieval['top1'][e].mean():.3f}"
                      for e in data.ENCODER_ORDER if e in retrieval["top1"])
          + f""". Encoder rank agreement on which scanner is hardest: """
